package com.kaushal.riskengine.evaluation;

import com.kaushal.riskengine.avro.DecisionType;

import java.time.LocalDate;
import java.time.ZoneOffset;
import java.util.Comparator;
import java.util.Locale;
import java.util.Map;

/**
 * Renders a {@link Evaluation.Result} as Markdown. Numbers only, plus the caveats that are
 * true of every run; interpretation belongs in the README, written by a person who has read
 * the numbers.
 */
final class ReportWriter {

    private ReportWriter() {
    }

    static String markdown(Evaluation.Result result, String dataSource) {
        StringBuilder md = new StringBuilder();
        Scorecard all = result.overall();

        md.append("# Evaluation\n\n");
        md.append("The engine's rules, run over %s labelled transactions. Generated by `./gradlew :evaluation:run` on %s.\n"
                .formatted(n(result.rows()), LocalDate.now(ZoneOffset.UTC)));
        md.append("Every number in this file is written by the evaluator; re-run it rather than editing by hand.\n\n");

        md.append("## Setup\n\n");
        md.append("- **Data:** %s. %s transactions on %s cards across %s merchants.\n"
                .formatted(dataSource, n(result.rows()), n(result.cards()), n(result.merchants())));
        md.append("- **Engine:** the production topology (`EnrichmentTopology` + `DecisionTopology`, the same classes the "
                + "live engine runs) hosted in `TopologyTestDriver`, fed in event-time order. Deterministic: the same data "
                + "gives the same numbers.\n");
        md.append("- **Labels:** each transaction's `is_fraud` travels through the pipeline in `labelledFraud` and comes "
                + "back on the engine's `Decision`. What's scored is what the engine emitted.\n");
        md.append("- **Thresholds:** exactly as in `RiskRules`. Chosen for the scripted demo scenarios and not tuned on "
                + "this data.\n");
        md.append("- **Run time:** %s for %s transactions (%s/s).\n\n"
                .formatted(duration(result.elapsed().toSeconds()), n(result.rows()),
                        n(Math.round(result.rows() / Math.max(1e-9, result.elapsed().toNanos() / 1e9)))));

        md.append("## Dataset\n\n");
        md.append("| Period | Transactions | Fraudulent | Base rate | Fraud amount |\n|---|---:|---:|---:|---:|\n");
        result.byFile().forEach((period, s) -> md.append(datasetRow(period, s)));
        if (result.byFile().size() > 1) {
            md.append(datasetRow("**all**", all));
        }

        md.append("\n## Declined (blocked outright)\n\n");
        md.append("A false positive here is a legitimate purchase that fails at the till.\n\n");
        confusionTable(md, result, true);

        md.append("\n## Flagged (REVIEW or DECLINE)\n\n");
        md.append("What a fraud team's review queue would contain.\n\n");
        confusionTable(md, result, false);

        md.append("\n## Per rule (all periods)\n\n");
        md.append("Each rule scored on its own: of the transactions it fired on, how many were fraud. "
                + "Lift is its precision divided by the base rate: how much better than random its hits are.\n\n");
        md.append("| Rule | Fires on | Of which fraud | Precision | Lift | Share of all fraud it fires on |\n"
                + "|---|---:|---:|---:|---:|---:|\n");
        all.rules().entrySet().stream()
                .sorted(Comparator.comparingLong((Map.Entry<String, Scorecard.RuleStats> e) -> -e.getValue().hits()))
                .forEach(e -> {
                    Scorecard.RuleStats r = e.getValue();
                    double precision = Scorecard.ratio(r.fraudHits(), r.hits());
                    md.append("| `%s` | %s | %s | %s | %s | %s |\n".formatted(
                            e.getKey(), n(r.hits()), n(r.fraudHits()), pct(precision),
                            all.baseRate() == 0 ? "–" : "%.1f×".formatted(precision / all.baseRate()),
                            pct(Scorecard.ratio(r.fraudHits(), all.fraud()))));
                });

        md.append("\n## Cards\n\n");
        md.append("| Cards with fraud | Caught (at least one fraudulent transaction flagged) | Median fraudulent transactions before the first catch |\n");
        md.append("|---:|---:|---:|\n");
        md.append("| %s | %s (%s) | %s |\n".formatted(
                n(all.fraudCards()), n(all.fraudCardsCaught()),
                pct(Scorecard.ratio(all.fraudCardsCaught(), all.fraudCards())),
                Double.isNaN(all.medianFraudsBeforeCatch()) ? "–" : "%.1f".formatted(all.medianFraudsBeforeCatch())));

        md.append("\n## Decisions\n\n| APPROVE | REVIEW | DECLINE |\n|---:|---:|---:|\n");
        md.append("| %s | %s | %s |\n".formatted(
                n(all.byDecision().getOrDefault(DecisionType.APPROVE, 0L)),
                n(all.byDecision().getOrDefault(DecisionType.REVIEW, 0L)),
                n(all.byDecision().getOrDefault(DecisionType.DECLINE, 0L))));

        md.append("""

                ## Caveats

                - **The fraud is simulated.** Sparkov injects fraud with a known generative process. These numbers measure \
                how well the rules match *that* process, not real-world fraud.
                - **Daily limits and risk tiers are invented.** Sparkov has neither, so the evaluation assigns them \
                deterministically per card (`SparkovMapping.cardholder`). Whatever `DAILY_LIMIT` and \
                `CUSTOMER_RISK_TIER` score here says more about those invented values than about fraud.
                - **Amounts are the dataset's own (USD).** The engine labels them EUR; rule thresholds such as the \
                2.00 card-testing ceiling apply to the number as given.
                - **Sparkov scatters merchant locations** up to roughly 100 km around each transaction, so \
                `GEO_VELOCITY`'s false positives here partly measure that scatter.
                - **Thresholds were not tuned on this data.** If they are, tune on `fraudTrain` and report `fraudTest` \
                only, or the headline number is fitted to its own test set.
                """);
        return md.toString();
    }

    private static String datasetRow(String period, Scorecard s) {
        return "| %s | %s | %s | %s | %s |\n".formatted(
                period, n(s.transactions()), n(s.fraud()), pct(s.baseRate()), money(s.fraudMinorTotal()));
    }

    private static void confusionTable(StringBuilder md, Evaluation.Result result, boolean declinedOnly) {
        md.append("| Period | Precision | Recall | F1 | False-positive rate | Fraud amount stopped | TP | FP | FN |\n"
                + "|---|---:|---:|---:|---:|---:|---:|---:|---:|\n");
        result.byFile().forEach((period, s) -> md.append(confusionRow(period, s, declinedOnly)));
        if (result.byFile().size() > 1) {
            md.append(confusionRow("**all**", result.overall(), declinedOnly));
        }
    }

    private static String confusionRow(String period, Scorecard s, boolean declinedOnly) {
        Scorecard.Confusion c = declinedOnly ? s.declined() : s.flagged();
        return "| %s | %s | %s | %.3f | %s | %s (%s) | %s | %s | %s |\n".formatted(
                period, pct(c.precision()), pct(c.recall()), c.f1(), pct(c.falsePositiveRate()),
                money(c.fraudMinorCaught()), pct(Scorecard.ratio(c.fraudMinorCaught(), s.fraudMinorTotal())),
                n(c.truePositives()), n(c.falsePositives()), n(c.falseNegatives()));
    }

    static String pct(double ratio) {
        double p = ratio * 100;
        return p != 0 && Math.abs(p) < 1 ? String.format(Locale.ROOT, "%.2f%%", p) : String.format(Locale.ROOT, "%.1f%%", p);
    }

    static String n(long value) {
        return String.format(Locale.ROOT, "%,d", value);
    }

    static String money(long minor) {
        return String.format(Locale.ROOT, "$%,d", Math.round(minor / 100.0));
    }

    private static String duration(long seconds) {
        return seconds >= 60 ? "%dm %02ds".formatted(seconds / 60, seconds % 60) : seconds + "s";
    }
}
